namespace AgentDeck.Status;

/// <summary>
/// Состояние тайла, определяющее вид точки статуса и тонировку рамки.
/// </summary>
public enum TileStatus
{
    /// <summary>
    /// Процесс не запущен — тайл показывает плейсхолдер.
    /// </summary>
    Placeholder,

    /// <summary>
    /// Процесс запущен и жив. Состояний у него не разобрать: так живёт обычный
    /// терминал, у которого «работает» и «ждёт ввода» с экрана не различить.
    /// </summary>
    Running,

    /// <summary>
    /// Агент занят: модель обрабатывает запрос, на экране висит маркер работы.
    /// </summary>
    Working,

    /// <summary>
    /// Агент отработал запрос и ждёт ввода пользователя.
    /// </summary>
    AwaitingInput,

    /// <summary>
    /// Агент запросил подтверждение действия.
    /// </summary>
    AwaitingPermission,

    /// <summary>
    /// Процесс завершился с нулевым кодом.
    /// </summary>
    Finished,

    /// <summary>
    /// Процесс завершился с ненулевым кодом.
    /// </summary>
    Crashed,
}
